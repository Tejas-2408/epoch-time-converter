// Secure and Reactive DOM Engine

// To handle Single Page Applications (SPAs) safely, this script uses a MutationObserver. It includes architectural safeguards to prevent infinite mutation loop rendering and eliminates Cross-Site Scripting (XSS) risks.

let extensionSettings = { enabled: true, timezone: 'LOCAL' };

// Strict regex matching 10-digit or 13-digit Unix timestamps.
//
// Only *standalone* numbers are matched. A plain `\b` boundary also matched
// digits embedded in URLs and identifiers (e.g. `/orders/1779313371`,
// `?id=1779313371`, `ORD-1779313371`, `1779313371.jpg`), which produced
// confusing conversions. Instead:
//   - Before the number: start of text, whitespace, an opening bracket/quote,
//     a comma, or a JSON-style `":` key separator.
//   - After the number: end of text, whitespace, a closing bracket/quote,
//     `,` / `;`, or sentence punctuation (`.`, `:`, `!`, `?`) that is itself
//     followed by whitespace or end of text (so `1779313371.5` or
//     `1779313371.png` are rejected).
const EPOCH_REGEX =
  /(?<=^|[\s(\[{"'\u201C\u2018,]|["']:)(1\d{9}|2\d{9}|1\d{12})(?=$|[\s)\]}"'\u201D\u2019,;]|[.:!?](?=$|\s))/g;

// ---------------------------------------------------------------------------
// Human-readable timestamp detection
// ---------------------------------------------------------------------------
// If an epoch already has a human-readable date/time right next to it — from
// this extension, an older build, another converter extension, or the page
// itself (e.g. `1779313371 (26 July 2026)`) — it must not be converted again.

const MONTH =
  '(?:jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|june?|july?|aug(?:ust)?|' +
  'sep(?:t(?:ember)?)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?)';
const WEEKDAY =
  '(?:mon(?:day)?|tue(?:s(?:day)?)?|wed(?:nesday)?|thu(?:r(?:s(?:day)?)?)?|' +
  'fri(?:day)?|sat(?:urday)?|sun(?:day)?)';

const HUMAN_DATE_PATTERNS = [
  // 2026-07-26, 2026/07/26, 2026.07.26 (optionally followed by a time / ISO "T")
  '\\d{4}[-/.]\\d{1,2}[-/.]\\d{1,2}(?!\\d)',
  // 26/07/2026, 7-26-26, 26.07.2026
  '\\d{1,2}[-/.]\\d{1,2}[-/.]\\d{2,4}(?!\\d)',
  // 26 July 2026, 26th of July, 26-Jul-2026, 26 Jul
  `\\d{1,2}(?:st|nd|rd|th)?(?:\\s+of)?[\\s\\-/.,]*${MONTH}\\b`,
  // July 26, 2026 / Jul 26 / July 2026
  `${MONTH}\\.?[\\s\\-/.,]+\\d{1,4}(?!\\d)`,
  // Mon, 20 Jul 2026 ... / Monday July 20 ...
  `${WEEKDAY}\\.?,?\\s+(?:\\d|${MONTH}\\b)`,
  // 21:42, 21:42:51, 9:42 PM
  '\\d{1,2}:\\d{2}(?::\\d{2})?(?!\\d)',
  // 5 minutes ago, an hour ago, 3 days ago
  '(?:\\d+|an?|one)\\s+(?:sec(?:ond)?s?|min(?:ute)?s?|hours?|hrs?|days?|weeks?|months?|years?|yrs?)\\s+ago\\b',
  // in 5 minutes / in 3 days
  'in\\s+(?:\\d+|an?|one)\\s+(?:sec(?:ond)?s?|min(?:ute)?s?|hours?|hrs?|days?|weeks?|months?|years?|yrs?)\\b',
  // just now / today / yesterday / tomorrow
  '(?:just\\s+now|today|yesterday|tomorrow)\\b'
];
const HUMAN_DATE = `(?:${HUMAN_DATE_PATTERNS.join('|')})`;

// Characters that typically sit between an epoch and an annotated date:
// whitespace, brackets, quotes, dashes, arrows, pipes, bullets and
// clock/calendar emoji used by converter extensions.
const SEPARATOR =
  '[\\s\\[\\](){}<>"\'\\u201C\\u201D\\u2018\\u2019\\-\\u2013\\u2014=:|,;~\\u2022\\u00B7@' +
  '\\u2192\\u21D2\\u00BB\\u00AB\\u231A\\u23F0\\u23F1\\u23F2\\uFE0F' +
  '\\u{1F550}-\\u{1F567}\\u{1F4C5}\\u{1F4C6}\\u{1F5D3}]';

// Human date immediately AFTER the epoch: `1779313371 (26 July 2026)`
const HUMAN_DATE_AFTER_REGEX = new RegExp(`^${SEPARATOR}*${HUMAN_DATE}`, 'iu');
// Human date immediately BEFORE the epoch: `26 July 2026 - 1779313371`
const HUMAN_DATE_BEFORE_REGEX = new RegExp(`${HUMAN_DATE}${SEPARATOR}*$`, 'iu');
// Human date anywhere (used for tooltip-style attributes)
const HUMAN_DATE_ANYWHERE_REGEX = new RegExp(HUMAN_DATE, 'iu');

// How much neighbouring text (across sibling nodes) to inspect.
const ADJACENT_TEXT_LIMIT = 80;

const NON_CONTENT_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEMPLATE']);

// Text generated by this extension looks like:
//   1779313371 [2026-05-20 21:42:51 IST]
// If a user copies that converted text into another tab, the content script
// must treat it as already converted instead of appending the time again.
const CURRENT_CONVERTED_SUFFIX_REGEX =
  /^\s*\[\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}\s+[^\]]+\]/;

// Older builds used a clock marker in the bracketed suffix. Keep recognizing
// that form too so previously copied content is still idempotent.
const LEGACY_CONVERTED_SUFFIX_REGEX = /^\s*\[\uD83D\uDD52[^\]]*\]/u;

function hasConvertedSuffix(text, indexAfterMatch) {
  const suffix = text.slice(indexAfterMatch);
  return (
    CURRENT_CONVERTED_SUFFIX_REGEX.test(suffix) ||
    LEGACY_CONVERTED_SUFFIX_REGEX.test(suffix)
  );
}

/**
 * Collects up to `limit` characters of rendered text that come immediately
 * before (`forward === false`) or after (`forward === true`) `node` in
 * document order. Other converter extensions often put their human date in a
 * sibling element (e.g. `<span>1779313371</span><span>26 July 2026</span>`),
 * so looking only inside the current text node is not enough.
 */
function collectAdjacentText(node, forward, limit) {
  if (!node || !document.body || !document.body.contains(node)) return '';

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) =>
      n.parentElement && NON_CONTENT_TAGS.has(n.parentElement.tagName)
        ? NodeFilter.FILTER_REJECT
        : NodeFilter.FILTER_ACCEPT
  });
  walker.currentNode = node;

  let collected = '';
  while (collected.length < limit) {
    const next = forward ? walker.nextNode() : walker.previousNode();
    if (!next) break;
    collected = forward
      ? `${collected} ${next.nodeValue}`
      : `${next.nodeValue} ${collected}`;
  }
  return forward ? collected.slice(0, limit) : collected.slice(-limit);
}

/**
 * True if the epoch is an identifier inside a link — i.e. the surrounding
 * `<a href>` points at a URL that contains the very same number
 * (e.g. `<a href="/orders/1779313371">1779313371</a>`).
 */
function isLinkIdentifier(node, digits) {
  const parentEl = node && node.parentElement;
  if (!parentEl) return false;
  const anchor = parentEl.closest('a[href]');
  return !!anchor && (anchor.getAttribute('href') || '').includes(digits);
}

/**
 * True if the element wrapping the epoch already exposes a human-readable
 * date through a tooltip-style attribute (a common pattern for converter
 * extensions and many web apps).
 */
function hasHumanDateAttribute(node) {
  const parentEl = node && node.parentElement;
  if (!parentEl) return false;
  return ['title', 'aria-label', 'data-tooltip', 'data-original-title'].some((attr) => {
    const value = parentEl.getAttribute(attr);
    return !!value && HUMAN_DATE_ANYWHERE_REGEX.test(value);
  });
}

/**
 * Decides whether the epoch at `offset` in `fullText` should be left alone
 * because a human-readable timestamp (in any format) already sits next to it.
 */
function hasAdjacentHumanDate(fullText, offset, matchLength, node) {
  const end = offset + matchLength;
  if (hasConvertedSuffix(fullText, end)) return true;

  let after = fullText.slice(end, end + ADJACENT_TEXT_LIMIT);
  let before = fullText.slice(Math.max(0, offset - ADJACENT_TEXT_LIMIT), offset);

  if (HUMAN_DATE_AFTER_REGEX.test(after) || HUMAN_DATE_BEFORE_REGEX.test(before)) {
    return true;
  }

  // Only reach into neighbouring nodes when the epoch is close to the edge of
  // its own text node. Because the regexes are anchored (only separators may
  // sit between the epoch and the date), unrelated text in between still
  // prevents a false match.
  if (node) {
    if (fullText.length - end < ADJACENT_TEXT_LIMIT) {
      after += collectAdjacentText(node, true, ADJACENT_TEXT_LIMIT);
      if (HUMAN_DATE_AFTER_REGEX.test(after)) return true;
    }
    if (offset < ADJACENT_TEXT_LIMIT) {
      before = collectAdjacentText(node, false, ADJACENT_TEXT_LIMIT) + before;
      if (HUMAN_DATE_BEFORE_REGEX.test(before)) return true;
    }
    if (hasHumanDateAttribute(node)) return true;
  }

  return false;
}

/** True if this epoch occurrence must not be converted. */
function shouldSkipEpoch(match, offset, fullText, node) {
  if (isLinkIdentifier(node, match)) return true;
  return hasAdjacentHumanDate(fullText, offset, match.length, node);
}

// Any element matching this selector is treated as a "live editing surface" —
// text/code editors and input-like widgets — and is never touched by the
// converter. Rewriting a text node's value while a user's cursor/selection is
// anchored inside it forces the browser to reset that cursor to the start of
// the node, which is what caused typing, caret position and copy/paste to
// break in unrelated editor panes elsewhere on the page.
const EDITABLE_SURFACE_SELECTOR = [
  '[contenteditable]',
  'input',
  'textarea',
  '[role="textbox"]',
  '[role="combobox"]',
  '[role="searchbox"]',
  '.CodeMirror',
  '.cm-editor',
  '.monaco-editor',
  '.ace_editor',
  '.ProseMirror',
  '[data-slate-editor]'
].join(',');

/**
 * True if `el` is, or sits inside, a live editing surface (a text box, rich
 * text editor or code editor) that the converter must never rewrite.
 */
function isEditableSurface(el) {
  if (!el || el.nodeType !== Node.ELEMENT_NODE) return false;

  const host = el.closest(EDITABLE_SURFACE_SELECTOR);
  if (!host) return false;

  // A `contenteditable="false"` element explicitly opts back out, even when
  // nested inside a larger editable ancestor.
  if (host.hasAttribute('contenteditable')) {
    return host.getAttribute('contenteditable') !== 'false';
  }

  return true;
}

// Initialize configurations from chrome storage
chrome.storage.local.get({ enabled: true, timezone: 'LOCAL' }, (items) => {
  extensionSettings = items;
  if (extensionSettings.enabled) {
    runConversion(document.body);
  }
});

// Watch for configuration shifts dynamically without requiring a page reload
chrome.storage.onChanged.addListener((changes) => {
  if (changes.enabled) extensionSettings.enabled = changes.enabled.newValue;
  if (changes.timezone) extensionSettings.timezone = changes.timezone.newValue;
  
  if (extensionSettings.enabled) {
    runConversion(document.body);
  }
});

function convertText(text, node = null) {
  return text.replace(EPOCH_REGEX, (match, _timestamp, offset, fullText) => {
    if (shouldSkipEpoch(match, offset, fullText, node)) {
      return match;
    }

    let timestamp = parseInt(match, 10);
    if (match.length === 10) timestamp *= 1000;

    try {
      // Configure strict 24-hour token options
      const options = {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hourCycle: 'h23', // Forces 24-hour cycle (00-23)
        timeZoneName: 'short' // Captures short code like IST, GMT, EST
      };
      
      if (extensionSettings.timezone !== 'LOCAL') {
        options.timeZone = extensionSettings.timezone;
      }
      
      // Use 'en-US' as a deterministic base locale to extract layout parts cleanly
      const formatter = new Intl.DateTimeFormat('en-US', options);
      const parts = formatter.formatToParts(new Date(timestamp));
      
      // Map the parts array into an easily queryable object map
      const p = Object.fromEntries(parts.map(part => [part.type, part.value]));
      
      // Construct exactly: yyyy-mm-dd HH:MM:ss TZ
      const humanTime = `${p.year}-${p.month}-${p.day} ${p.hour}:${p.minute}:${p.second} ${p.timeZoneName}`;
      
      return `${match} [${humanTime}]`;
    } catch (e) {
      return match; // Keep unchanged if date calculations fail
    }
  });
}

function runConversion(rootNode) {
  if (!rootNode) return;

  // Never walk into a live editing surface at all — skip the whole subtree.
  if (rootNode.nodeType === Node.ELEMENT_NODE && isEditableSurface(rootNode)) {
    return;
  }

  const walker = document.createTreeWalker(
    rootNode,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode: (node) => {
        const parentEl = node.parentElement;
        if (!parentEl) return NodeFilter.FILTER_REJECT;

        const parentTag = parentEl.tagName;
        if (['SCRIPT', 'STYLE', 'CODE', 'INPUT', 'TEXTAREA'].includes(parentTag)) {
          return NodeFilter.FILTER_REJECT;
        }

        // Skip text that lives inside any editor / input-like widget so we
        // never mutate a node the user might currently be typing into.
        if (isEditableSurface(parentEl)) {
          return NodeFilter.FILTER_REJECT;
        }

        return NodeFilter.FILTER_ACCEPT;
      }
    }
  );

  let currentNode;
  while ((currentNode = walker.nextNode())) {
    const originalValue = currentNode.nodeValue;
    const alteredValue = convertText(originalValue, currentNode);
    if (originalValue !== alteredValue) {
      currentNode.nodeValue = alteredValue; 
    }
  }
}

// Performance and Security Shielded Mutation Observer
const observer = new MutationObserver((mutations) => {
  if (!extensionSettings.enabled) return;

  // Temporarily pause monitoring transformations to completely neutralize infinite loops
  observer.disconnect();

  for (const mutation of mutations) {
    // If this mutation happened inside a live editing surface (e.g. a code
    // editor pane re-rendering as the user types), ignore it entirely —
    // don't even look at its added nodes. This is what previously caused
    // typing/cursor position/copy-paste to break in other editor panes.
    if (mutation.target && isEditableSurface(mutation.target)) {
      continue;
    }

    for (const node of mutation.addedNodes) {
      if (node.nodeType === Node.ELEMENT_NODE) {
        runConversion(node);
      } else if (node.nodeType === Node.TEXT_NODE) {
        const parentEl = node.parentElement;
        if (!parentEl) continue;

        const pTag = parentEl.tagName;
        if (['SCRIPT', 'STYLE', 'CODE'].includes(pTag)) continue;
        if (isEditableSurface(parentEl)) continue;

        const converted = convertText(node.nodeValue, node);
        if (converted !== node.nodeValue) node.nodeValue = converted;
      }
    }
  }

  // Re-engage execution pipeline
  startObserving();
});

function startObserving() {
  observer.observe(document.body, {
    childList: true,
    subtree: true
  });
}

// Trigger initial entrypoint initialization
if (document.body) startObserving();
